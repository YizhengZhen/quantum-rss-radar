def build_digest_email_text(
    digest: DigestConfig,
    pairs: list[tuple],
    sources: dict[str, SourceConfig],
    feed_configs: dict[str, FeedConfig] | None = None,
) -> str:
    date_str = datetime.now().strftime("%Y-%m-%d")
    lines = [
        "=" * 60,
        f"QUANTUM RSS RADAR — {digest.name}",
        date_str,
        "=" * 60,
        "",
        f"Total papers: {len(pairs)}  (min score: {digest.min_score})",
        "",
        f"TOP {len(pairs)} PAPERS BY SCORE",
        "-" * 40,
        "",
    ]

    for i, (paper, analysis) in enumerate(pairs, 1):
        src_display, _ = _resolve_feed_config(paper, sources or {}, feed_configs or {})
        authors = ", ".join(paper.authors[:3])
        if len(paper.authors) > 3:
            authors += " et al."
        lines += [
            f"{i}. {paper.title}",
            f"   Score: {analysis.relevance_score:.1f}/10",
            f"   Source: {src_display}  |  Direction: {analysis.direction or 'General / Other'}",
            f"   Authors: {authors}",
            f"   TL;DR: {analysis.tldr}",
            f"   Link: {paper.link}",
            "",
        ]

    lines += [
        "-" * 40,
        "Auto-generated by Quantum RSS Radar.",
        f"(c) {datetime.now().year}",
        "",
    ]
    return "\n".join(lines)


# ── Orchestrated sending ─────────────────────────────────────


def send_digests(
    config_dir: str = "config",
    config: Config | None = None,
    sources: dict[str, SourceConfig] | None = None,
    feed_configs: dict[str, FeedConfig] | None = None,
    archive_dir: str | None = None,
    today=None,
) -> dict[str, bool]:
    """Send all enabled digests that are due today.

    Returns:
        {digest_id: sent_ok}
    """
    if config is None:
        from .config_loader import load_config

        config = load_config()

    if not config.email_enabled:
        logger.info("Email sending disabled — skipping digests")
        return {}

    digests = load_digest_configs(config_dir)
    enabled = [d for d in digests if d.enabled]
    if not enabled:
        logger.info("No enabled digests found")
        return {}

    archive_dir = archive_dir or config.archive_dir
    records = history.load_jsonl_archive(archive_dir)
    today = today or datetime.now().date()

    results: dict[str, bool] = {}
    for digest in enabled:
        if not should_send_today(digest, today):
            logger.info(f"Digest '{digest.id}' not scheduled for {today} — skipping")
            continue

        selected = history.filter_by_digest(records, digest, today)
        pairs = history.records_to_pairs(selected)
        if not pairs:
            logger.warning(
                f"Digest '{digest.id}' is due but no papers matched — skipping"
            )
            results[digest.id] = False
            continue

        subject = digest.subject_template.format(
            name=digest.name, date=today.strftime("%Y-%m-%d")
        )
        html = build_digest_email_html(
            digest, pairs, sources or {}, config, feed_configs
        )
        text = build_digest_email_text(digest, pairs, sources or {}, feed_configs)

        ok = _send_smtp(subject, html, text, config)
        logger.info(
            f"Digest '{digest.id}' ({digest.name}) sent: {ok} ({len(pairs)} papers)"
        )
        results[digest.id] = ok

    return results
