# ── Calendar ─────────────────────────────────────────────────


def should_send_today(digest: DigestConfig, today=None) -> bool:
    """Whether this digest should be sent on `today`."""
    today = today or datetime.now().date()
    if digest.frequency == DigestType.WEEKDAY:
        return today.weekday() < 5  # Mon–Fri
    if digest.frequency == DigestType.WEEKLY:
        return today.weekday() == int(digest.schedule.get("weekday", 6))
    if digest.frequency == DigestType.MONTHLY:
        return today.day == int(digest.schedule.get("day_of_month", 1))
    if digest.frequency == DigestType.SEASONAL:
        return today.month % 3 == 1 and today.day == 1  # quarter start
    return False


